#!/usr/bin/env bash
# Runs a real WordPress site with AI Post Scheduler in a Claude Code cloud
# session (no Docker). Entry point: `make cloud-site` / `make cloud-site-stop`.
#
#   install   create the site (idempotent): copy of the WordPress core that the
#             test library installed, its own `aips_site` database, the plugin
#             symlinked from this checkout (edits are live), and the `ai` +
#             `ai-provider-for-google` plugins, as in docker-entrypoint.sh
#   start     install if needed, then serve it with PHP's built-in server
#   stop      stop the server (the site and its database are kept)
#   status    show whether the server is running
#   reset     stop, then delete the site files and its database
#
# Admin: $AIPS_SITE_URL/wp-admin (admin/admin). Real Gemini calls work when the
# environment has a network secret for generativelanguage.googleapis.com: the
# proxy swaps the dummy GOOGLE_API_KEY for the real key.
set -euo pipefail

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
HELPERS="$REPO_DIR/scripts/cloud-wp"
WP_CORE_DIR="${WP_CORE_DIR:-/tmp/wordpress}"
SITE_DIR="${AIPS_SITE_DIR:-/tmp/aips-site}"
PORT="${AIPS_SITE_PORT:-8080}"
URL="${AIPS_SITE_URL:-http://localhost:$PORT}"
DB_NAME="aips_site"
PID_FILE="$SITE_DIR/.server.pid"
LOG_FILE="$SITE_DIR/.server.log"
EXTRA_PLUGINS=(ai ai-provider-for-google)

running() {
	[[ -f "$PID_FILE" ]] && kill -0 "$(cat "$PID_FILE")" 2>/dev/null
}

ensure_db() {
	bash "$REPO_DIR/scripts/cloud-session-start.sh" --force >/dev/null
	if ! mysqladmin ping --silent >/dev/null 2>&1; then
		echo "MariaDB is not running; check the environment setup script." >&2
		exit 1
	fi
	mysql -uroot -e "CREATE DATABASE IF NOT EXISTS \`$DB_NAME\`;"
}

write_config() {
	cat > "$SITE_DIR/wp-config.php" <<PHP
<?php
// Generated by scripts/cloud-wp-site.sh for Claude Code cloud sessions.
define( 'DB_NAME', '$DB_NAME' );
define( 'DB_USER', 'root' );
define( 'DB_PASSWORD', '' );
define( 'DB_HOST', '127.0.0.1' );
define( 'DB_CHARSET', 'utf8mb4' );
define( 'DB_COLLATE', '' );
\$table_prefix = 'wp_';

define( 'WP_DEBUG', true );
define( 'WP_DEBUG_LOG', true );
define( 'WP_DEBUG_DISPLAY', false );
define( 'SCRIPT_DEBUG', true );
define( 'WP_MEMORY_LIMIT', '512M' );
define( 'DISABLE_WP_CRON', false );
define( 'WP_ENVIRONMENT_TYPE', 'local' );
define( 'AUTH_KEY', '$(head -c 32 /dev/urandom | base64 | tr -d '=+/')' );
define( 'SECURE_AUTH_KEY', '$(head -c 32 /dev/urandom | base64 | tr -d '=+/')' );
define( 'LOGGED_IN_KEY', '$(head -c 32 /dev/urandom | base64 | tr -d '=+/')' );
define( 'NONCE_KEY', '$(head -c 32 /dev/urandom | base64 | tr -d '=+/')' );

// Dummy key only: the session proxy injects the real one (network secret).
if ( getenv( 'GOOGLE_API_KEY' ) ) {
	define( 'GOOGLE_API_KEY', getenv( 'GOOGLE_API_KEY' ) );
}

// Route WordPress HTTP requests through the session proxy (port changes per session).
\$aips_proxy = getenv( 'HTTPS_PROXY' ) ?: getenv( 'https_proxy' );
if ( \$aips_proxy ) {
	define( 'WP_PROXY_HOST', parse_url( \$aips_proxy, PHP_URL_HOST ) );
	define( 'WP_PROXY_PORT', (string) parse_url( \$aips_proxy, PHP_URL_PORT ) );
	define( 'WP_PROXY_BYPASS_HOSTS', 'localhost, 127.0.0.1' );
}

if ( ! defined( 'ABSPATH' ) ) {
	define( 'ABSPATH', __DIR__ . '/' );
}
require_once ABSPATH . 'wp-settings.php';
PHP
}

install_plugin_zip() {
	local slug="$1" tmp
	[[ -d "$SITE_DIR/wp-content/plugins/$slug" ]] && return 0
	tmp="$(mktemp -d)"
	echo "Downloading plugin $slug from wordpress.org..."
	if curl -fsSL --retry 3 -o "$tmp/$slug.zip" "https://downloads.wordpress.org/plugin/$slug.latest-stable.zip"; then
		unzip -q "$tmp/$slug.zip" -d "$SITE_DIR/wp-content/plugins/"
	else
		echo "WARNING: could not download $slug; the site will run without it." >&2
	fi
	rm -rf "$tmp"
}

install_site() {
	if [[ ! -f "$WP_CORE_DIR/wp-settings.php" ]]; then
		echo "WordPress core missing at $WP_CORE_DIR; the environment setup script installs it." >&2
		exit 1
	fi
	ensure_db
	if [[ ! -f "$SITE_DIR/wp-settings.php" ]]; then
		mkdir -p "$SITE_DIR"
		cp -R "$WP_CORE_DIR/." "$SITE_DIR/"
	fi
	[[ -f "$SITE_DIR/wp-config.php" ]] || write_config
	mkdir -p "$SITE_DIR/wp-content/mu-plugins"
	cp "$HELPERS/aips-cloud-proxy.php" "$SITE_DIR/wp-content/mu-plugins/"
	ln -sfn "$REPO_DIR/ai-post-scheduler" "$SITE_DIR/wp-content/plugins/ai-post-scheduler"
	for slug in "${EXTRA_PLUGINS[@]}"; do install_plugin_zip "$slug"; done
	php "$HELPERS/install.php" "$SITE_DIR" "$URL" admin admin "${EXTRA_PLUGINS[@]}" ai-post-scheduler
}

start_site() {
	if running; then
		echo "Already running: $URL (admin: $URL/wp-admin, admin/admin)"
		return 0
	fi
	install_site
	nohup php -S "0.0.0.0:$PORT" -t "$SITE_DIR" "$HELPERS/router.php" >"$LOG_FILE" 2>&1 &
	echo $! > "$PID_FILE"
	for _ in $(seq 1 20); do
		curl -s -o /dev/null "$URL/wp-login.php" && break
		sleep 0.5
	done
	if ! running; then
		echo "Server failed to start; see $LOG_FILE" >&2
		exit 1
	fi
	echo "WordPress is running: $URL (admin: $URL/wp-admin, admin/admin)"
	echo "Server log: $LOG_FILE · PHP/WordPress errors: $SITE_DIR/wp-content/debug.log"
}

stop_site() {
	if running; then
		kill "$(cat "$PID_FILE")" && rm -f "$PID_FILE"
		echo "Stopped the WordPress server (site and database kept)."
	else
		rm -f "$PID_FILE"
		echo "WordPress server is not running."
	fi
}

case "${1:-start}" in
	install) install_site ;;
	start) start_site ;;
	stop) stop_site ;;
	status) if running; then echo "Running: $URL (pid $(cat "$PID_FILE"))"; else echo "Not running."; fi ;;
	reset)
		stop_site
		[[ "$SITE_DIR" == /tmp/* ]] && rm -rf "$SITE_DIR"
		mysql -uroot -e "DROP DATABASE IF EXISTS \`$DB_NAME\`;" 2>/dev/null || true
		echo "Deleted the site files and the $DB_NAME database."
		;;
	*) echo "usage: $0 install|start|stop|status|reset" >&2; exit 2 ;;
esac
