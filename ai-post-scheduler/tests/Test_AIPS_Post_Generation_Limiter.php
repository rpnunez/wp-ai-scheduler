class Test_AIPS_Post_Generation_Limiter extends WP_UnitTestCase {

	/**
	 * @var AIPS_Post_Generation_Limiter
	 */
	private $limiter;

	/**
	 * @var AIPS_Config
	 */
	private $config;

	public function setUp(): void {
		parent::setUp();
		$this->config  = AIPS_Config::get_instance();
		$this->limiter = new AIPS_Post_Generation_Limiter($this->config);
		$this->limiter->clear_cache();
		delete_transient(AIPS_Post_Generation_Limiter::NOTIF_COOLDOWN_TRANSIENT);

		// Clean up any test options
		delete_option('aips_disable_generation_limiter');
		delete_option('aips_generation_limiter_bypass_manual');
		delete_option('aips_generation_limiter_post_types');
		delete_option('aips_generation_limiter_post_statuses');
		delete_option('aips_generation_limit_hourly');
		delete_option('aips_generation_limit_daily');
		delete_option('aips_generation_limit_weekly');
		delete_option('aips_generation_limit_monthly');
	}

	public function tearDown(): void {
		$this->limiter->clear_cache();
		delete_transient(AIPS_Post_Generation_Limiter::NOTIF_COOLDOWN_TRANSIENT);
		delete_option('aips_disable_generation_limiter');
		delete_option('aips_generation_limiter_bypass_manual');
		delete_option('aips_generation_limiter_post_types');
		delete_option('aips_generation_limiter_post_statuses');
		delete_option('aips_generation_limit_hourly');
		delete_option('aips_generation_limit_daily');
		delete_option('aips_generation_limit_weekly');
		delete_option('aips_generation_limit_monthly');
		parent::tearDown();
	}

	/**
	 * Create a dummy post marked as generated by AIPS.
	 *
	 * @param string $status    Post status.
	 * @param string $post_date MySQL date string.
	 * @param bool   $mark_aips Whether to mark with _aips_generated_post meta.
	 * @param string $post_type Post type.
	 * @return int Post ID.
	 */
	private function create_test_post(string $status = 'publish', string $post_date = '', bool $mark_aips = true, string $post_type = 'post'): int {
		$now_mysql = current_time('mysql');
		$post_id   = $this->factory->post->create(
			array(
				'post_type'     => $post_type,
				'post_status'   => $status,
				'post_date'     => $post_date ?: $now_mysql,
				'post_date_gmt' => $post_date ? get_gmt_from_date($post_date) : current_time('mysql', 1),
			)
		);

		if ($mark_aips) {
			update_post_meta($post_id, AIPS_Post_Generation_Limiter::META_KEY_GENERATED, '1');
		}

		return $post_id;
	}

	public function test_default_configuration_and_limits() {
		$this->assertTrue($this->limiter->is_enabled());
		$this->assertTrue($this->limiter->is_manual_bypass_enabled());

		$limits = $this->limiter->get_limits();
		$this->assertSame(50, $limits['hourly']);
		$this->assertSame(200, $limits['daily']);
		$this->assertSame(1000, $limits['weekly']);
		$this->assertSame(3500, $limits['monthly']);

		$types = $this->limiter->get_counted_post_types();
		$this->assertContains('post', $types);

		$statuses = $this->limiter->get_counted_post_statuses();
		$this->assertContains('publish', $statuses);
		$this->assertContains('draft', $statuses);
		$this->assertContains('pending', $statuses);
		$this->assertContains('future', $statuses);
		$this->assertContains('private', $statuses);
	}

	public function test_disabled_limiter_allows_generation() {
		update_option('aips_disable_generation_limiter', 1);
		update_option('aips_generation_limit_hourly', 1);

		// Create 2 generated posts
		$this->create_test_post();
		$this->create_test_post();
		$this->limiter->clear_cache();

		$this->assertFalse($this->limiter->is_enabled());
		$result = $this->limiter->check_limits(false);
		$this->assertTrue($result);
	}

	public function test_manual_bypass_allows_generation() {
		update_option('aips_disable_generation_limiter', 0);
		update_option('aips_generation_limiter_bypass_manual', 1);
		update_option('aips_generation_limit_hourly', 1);

		// Create 2 generated posts
		$this->create_test_post();
		$this->create_test_post();
		$this->limiter->clear_cache();

		// Manual run should pass because bypass is enabled
		$result = $this->limiter->check_limits(true);
		$this->assertTrue($result);

		// Non-manual run should fail
		$result_auto = $this->limiter->check_limits(false);
		$this->assertWPError($result_auto);
		$this->assertSame('aips_generation_rate_limit_exceeded', $result_auto->get_error_code());
	}

	public function test_counting_only_aips_generated_posts() {
		update_option('aips_generation_limit_hourly', 10);

		// Create 2 AIPS-generated posts
		$this->create_test_post('publish', '', true);
		$this->create_test_post('publish', '', true);

		// Create 2 normal non-AIPS posts
		$this->create_test_post('publish', '', false);
		$this->create_test_post('publish', '', false);

		$this->limiter->clear_cache();

		$count = $this->limiter->get_count_for_period('hourly');
		$this->assertSame(2, $count);
	}

	public function test_status_filtering() {
		// Only count 'publish' and 'draft'
		update_option('aips_generation_limiter_post_statuses', array('publish', 'draft'));

		$this->create_test_post('publish', '', true);
		$this->create_test_post('draft', '', true);
		$this->create_test_post('pending', '', true);
		$this->create_test_post('private', '', true);

		$this->limiter->clear_cache();

		$count = $this->limiter->get_count_for_period('hourly');
		$this->assertSame(2, $count);
	}

	public function test_post_type_filtering() {
		// Only count 'post'
		update_option('aips_generation_limiter_post_types', array('post'));

		$this->create_test_post('publish', '', true, 'post');
		$this->create_test_post('publish', '', true, 'post');
		$this->create_test_post('publish', '', true, 'page');

		$this->limiter->clear_cache();

		$count = $this->limiter->get_count_for_period('hourly');
		$this->assertSame(2, $count);

		// Specific post type count
		$page_count = $this->limiter->get_count_for_period('hourly', 'page');
		$this->assertSame(1, $page_count);
	}

	public function test_uncounted_post_type_bypasses_ceiling() {
		update_option('aips_generation_limit_hourly', 1);
		// Only 'post' is counted
		update_option('aips_generation_limiter_post_types', array('post'));

		// 1 post generated -> ceiling reached for posts
		$this->create_test_post('publish', '', true, 'post');
		$this->limiter->clear_cache();

		$post_context = new class {
			public function get_creation_method() {
				return 'scheduled';
			}
			public function get_post_type() {
				return 'post';
			}
		};

		$page_context = new class {
			public function get_creation_method() {
				return 'scheduled';
			}
			public function get_post_type() {
				return 'page';
			}
		};

		// Generating a 'post' must be blocked
		$result_post = $this->limiter->check_limits(false, $post_context);
		$this->assertWPError($result_post);
		$this->assertSame('aips_generation_rate_limit_exceeded', $result_post->get_error_code());

		// Generating a 'page' (uncounted) must bypass and succeed
		$result_page = $this->limiter->check_limits(false, $page_context);
		$this->assertTrue($result_page);
	}

	public function test_polymorphic_get_limits_and_filter() {
		add_filter(
			'aips_generation_limits_for_post_type',
			function ($limits, $post_type) {
				if ('page' === $post_type) {
					$limits['hourly'] = 2;
				}
				return $limits;
			},
			10,
			2
		);

		$default_limits = $this->limiter->get_limits();
		$this->assertSame(50, $default_limits['hourly']);

		$page_limits = $this->limiter->get_limits('page');
		$this->assertSame(2, $page_limits['hourly']);
	}

	public function test_ceiling_breach_returns_wp_error() {
		update_option('aips_generation_limit_hourly', 2);

		$this->create_test_post();
		$this->create_test_post();
		$this->limiter->clear_cache();

		$result = $this->limiter->check_limits(false);
		$this->assertWPError($result);
		$this->assertSame('aips_generation_rate_limit_exceeded', $result->get_error_code());

		$data = $result->get_error_data();
		$this->assertIsArray($data);
		$this->assertSame('hourly', $data['period']);
		$this->assertSame(2, $data['limit']);
		$this->assertSame(2, $data['count']);
	}

	public function test_action_fired_on_breach() {
		update_option('aips_generation_limit_hourly', 1);
		$this->create_test_post();
		$this->limiter->clear_cache();

		$action_fired = false;
		$captured     = array();

		add_action(
			'aips_generation_rate_limit_exceeded',
			function ($period, $limit, $count, $context, $post_type = null) use (&$action_fired, &$captured) {
				$action_fired = true;
				$captured     = array(
					'period'    => $period,
					'limit'     => $limit,
					'count'     => $count,
					'post_type' => $post_type,
				);
			},
			10,
			5
		);

		$this->limiter->check_limits(false);

		$this->assertTrue($action_fired);
		$this->assertSame('hourly', $captured['period']);
		$this->assertSame(1, $captured['limit']);
		$this->assertSame(1, $captured['count']);
		$this->assertNull($captured['post_type']);
	}

	public function test_conjunction_single_count_guarantee() {
		// When a post matches multiple counted post types and counted statuses,
		// it must only be counted exactly once (AND conjunct in SQL).
		update_option('aips_generation_limiter_post_types', array('post', 'page'));
		update_option('aips_generation_limiter_post_statuses', array('publish', 'draft', 'pending'));

		$this->create_test_post('publish', '', true, 'post');
		$this->limiter->clear_cache();

		$count = $this->limiter->get_count_for_period('hourly');
		$this->assertSame(1, $count, 'A single post matching both post_type and post_status must only be counted once.');
	}

	public function test_two_tier_limit_evaluation() {
		// Set global hourly limit to 10
		update_option('aips_generation_limit_hourly', 10);
		update_option('aips_generation_limiter_post_types', array('post', 'page'));

		// Custom filter: 'page' is limited to 2 posts per hour
		add_filter(
			'aips_generation_limits_for_post_type',
			function ($limits, $post_type) {
				if ('page' === $post_type) {
					$limits['hourly'] = 2;
				}
				return $limits;
			},
			10,
			2
		);

		// Create 2 pages
		$this->create_test_post('publish', '', true, 'page');
		$this->create_test_post('publish', '', true, 'page');
		$this->limiter->clear_cache();

		// Check limits for 'page' -> should fail Tier 1 (page limit of 2 reached)
		$result_page = $this->limiter->check_limits(false, null, 'page');
		$this->assertWPError($result_page);
		$this->assertSame('aips_generation_rate_limit_exceeded', $result_page->get_error_code());
		$this->assertStringContainsString('page', $result_page->get_error_message());

		// Check limits for 'post' -> should pass because post count is 0 and aggregate count is 2 (below global 10)
		$result_post = $this->limiter->check_limits(false, null, 'post');
		$this->assertTrue($result_post);

		// Now add 8 more posts to hit the global limit of 10 (2 pages + 8 posts = 10)
		for ($i = 0; $i < 8; $i++) {
			$this->create_test_post('publish', '', true, 'post');
		}
		$this->limiter->clear_cache();

		// Check limits for 'post' -> should now fail Tier 2 (global aggregate limit of 10 reached)
		$result_global_fail = $this->limiter->check_limits(false, null, 'post');
		$this->assertWPError($result_global_fail);
		$this->assertSame('aips_generation_rate_limit_exceeded', $result_global_fail->get_error_code());
	}

	public function test_get_usage_structure() {
		update_option('aips_generation_limit_hourly', 5);
		$this->create_test_post();
		$this->limiter->clear_cache();

		$usage = $this->limiter->get_usage();

		$this->assertArrayHasKey('hourly', $usage);
		$this->assertArrayHasKey('daily', $usage);
		$this->assertArrayHasKey('weekly', $usage);
		$this->assertArrayHasKey('monthly', $usage);

		$this->assertSame(5, $usage['hourly']['limit']);
		$this->assertSame(1, $usage['hourly']['count']);
		$this->assertFalse($usage['hourly']['reached']);
	}

	public function test_pre_generate_filter_callback() {
