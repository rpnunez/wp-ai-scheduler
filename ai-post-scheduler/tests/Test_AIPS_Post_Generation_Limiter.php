	}

	public function test_post_statuses_sanitization() {
		$ui = new AIPS_Settings_UI();

		// Valid subset
		$sanitized = $ui->sanitize_generation_limiter_post_statuses(array('publish', 'draft', 'invalid_status'));
		$this->assertSame(array('publish', 'draft'), $sanitized);

		// Empty array fallback
		$fallback = $ui->sanitize_generation_limiter_post_statuses(array());
		$this->assertSame(array('publish', 'draft', 'pending', 'future', 'private'), $fallback);

		// Non-array fallback
		$non_array = $ui->sanitize_generation_limiter_post_statuses('publish');
		$this->assertSame(array('publish', 'draft', 'pending', 'future', 'private'), $non_array);
	}

	public function test_post_types_sanitization() {
		$ui = new AIPS_Settings_UI();

		// Valid subset
		$sanitized = $ui->sanitize_generation_limiter_post_types(array('post', 'non_existent_cpt'));
		$this->assertSame(array('post'), $sanitized);

		// Empty array fallback to all selectable
		$fallback = $ui->sanitize_generation_limiter_post_types(array());
		$this->assertContains('post', $fallback);

		// Non-array fallback
		$non_array = $ui->sanitize_generation_limiter_post_types('post');
		$this->assertContains('post', $non_array);
	}

	public function test_cache_invalidation_on_option_update() {
		$this->limiter->init();

		$this->create_test_post('publish', '', true, 'post');
		$count1 = $this->limiter->get_count_for_period('hourly');
		$this->assertSame(1, $count1);

		// Trigger option update hook
		do_action('update_option_aips_generation_limiter_post_types', array('post'), array('post', 'page'), 'aips_generation_limiter_post_types');

		// Create another post
		$this->create_test_post('publish', '', true, 'post');

		// Since cache was cleared by the hook, the count should now reflect 2 without explicit manual clear_cache
		$count2 = $this->limiter->get_count_for_period('hourly');
		$this->assertSame(2, $count2);
	}

	public function test_defensive_context_resolution_with_arbitrary_object() {
		// Context with no get_post_type or get_id should not cause fatal error
		$arbitrary_context = (object) array('foo' => 'bar');
		$result = $this->limiter->check_limits(false, $arbitrary_context);
		$this->assertTrue($result);
	}
