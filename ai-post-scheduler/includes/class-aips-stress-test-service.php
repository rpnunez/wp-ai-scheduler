    /**
     * Drive the real Integration Manager for a set of field mappings and return
     * the per-field outcome it reports.
     *
     * The manager is wired to this service's AI service, so its generate_json /
     * generate_text calls land in the same call log the results panel reads,
     * and to a fixed in-memory mapping store so nothing is persisted.
     *
     * @param int    $post_id        Target post ID.
     * @param string $integration_id Integration identifier ('native_meta'|'acf').
     * @param string $source_key     Group/source key (post type for native meta).
     * @param array  $field_specs    List of ['field_key','field_type','field_label','custom_prompt'].
     * @return array<string, true|WP_Error> field_key => outcome.
     */
    private function run_integration_fields($post_id, $integration_id, $source_key, array $field_specs) {
        $mappings = array();

        foreach ($field_specs as $spec) {
            $mappings[] = (object) array(
                'template_id'    => self::SYNTHETIC_TEMPLATE_ID,
                'integration_id' => $integration_id,
                'source_key'     => $source_key,
                'field_key'      => $spec['field_key'],
                'field_label'    => isset($spec['field_label']) ? $spec['field_label'] : $spec['field_key'],
                'field_type'     => $spec['field_type'],
                'custom_prompt'  => isset($spec['custom_prompt']) ? $spec['custom_prompt'] : '',
                'is_active'      => 1,
            );
        }

        $repo    = new AIPS_Stress_Test_Fixed_Mappings_Repository($mappings);
        $manager = new AIPS_Integration_Manager($repo, $this->ai_service, null, $this->logger);

        $post_type     = get_post_type($post_id) ?: 'post';
        $context       = $this->build_context(0, $post_type, self::SYNTHETIC_TEMPLATE_ID);
        $template_stub  = (object) array('id' => self::SYNTHETIC_TEMPLATE_ID);

        $captured = array();
        $collector = function ($applied_post_id, $applied_integration_id, $results) use (&$captured, $post_id, $integration_id) {
            if ((int) $applied_post_id === (int) $post_id && $applied_integration_id === $integration_id) {
                $captured = $results;
            }
        };

        add_action('aips_integration_fields_applied', $collector, 10, 3);
        $manager->handle_post_generated($post_id, $template_stub, null, $context);
        remove_action('aips_integration_fields_applied', $collector, 10);

        return $captured;
    }

    /**
     * Turn per-field outcomes plus the written values into a case result.
     *
     * A field only counts as passing when the engine reported success AND a
     * non-empty value is actually readable back from storage.
     *
     * @param int    $post_id        Target post ID.
     * @param string $integration_id Integration identifier.
     * @param array  $field_specs    The specs that were generated.
     * @param array  $captured       field_key => true|WP_Error from the manager.
     * @param bool   $mention_calls  Append the AI-call count to the summary.
     * @return array<string, mixed>
     */
    private function summarize_field_results($post_id, $integration_id, $field_specs, $captured, $mention_calls = false) {
        $written   = array();
        $errors    = array();
        $non_empty = 0;

        foreach ($field_specs as $spec) {
            $key     = $spec['field_key'];
            $outcome = isset($captured[$key]) ? $captured[$key] : null;

            if (is_wp_error($outcome)) {
                $errors[] = $key . ': ' . $outcome->get_error_message();
                $written[$key] = null;
                continue;
            }

            $value         = $this->read_back_field($post_id, $integration_id, $key);
            $written[$key] = $value;

            $flat = is_array($value) ? wp_json_encode($value) : (string) $value;

            if (trim((string) $flat) !== '') {
                $non_empty++;
            }
        }

        $expected = count($field_specs);
        $passed   = empty($errors) && $non_empty === $expected;

        $summary = sprintf(
            /* translators: 1: fields written, 2: fields expected */
            __('%1$d of %2$d fields generated and written.', 'ai-post-scheduler'),
            $non_empty,
            $expected
        );

        if ($mention_calls) {
            $call_count = count($this->ai_service->get_call_log());
            $summary   .= ' ' . sprintf(
                /* translators: %d: number of AI calls */
                _n('%d AI call.', '%d AI calls.', $call_count, 'ai-post-scheduler'),
                $call_count
            );
        }

        return array(
            'status'       => $passed ? 'passed' : 'failed',
            'summary'      => $summary,
            'error'        => empty($errors) ? null : implode(' | ', $errors),
            'ai_value'     => $this->first_ai_response_text(),
            'plugin_value' => $written,
            'artifacts'    => array('post_ids' => array((int) $post_id)),
        );
    }

    /**
     * Read a written field value back from storage for verification.
     *
     * @param int    $post_id        Target post ID.
     * @param string $integration_id Integration identifier.
     * @param string $field_key      Field/meta key.
     * @return mixed
     */
    private function read_back_field($post_id, $integration_id, $field_key) {
        if ($integration_id === 'acf' && function_exists('get_field')) {
            return get_field($field_key, $post_id);
        }

        return get_post_meta($post_id, $field_key, true);
    }

