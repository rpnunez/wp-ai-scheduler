/**
 * Resilience configuration for interactive stress-test requests.
 *
 * The page is intended to validate the complete pipeline, so one transient
 * timeout or provider 503 should be retried quickly. Circuit-breaker and local
 * rate-limit settings continue to mirror the site's real configuration.
 */
class AIPS_Stress_Test_Resilience_Config {

    /** @var AIPS_Config */
    private $config;

    /**
     * @param AIPS_Config $config Site configuration.
     */
    public function __construct($config) {
        $this->config = $config;
    }

    /**
     * Use one short retry after the initial provider attempt.
     *
     * @return array<string,mixed>
     */
    public function get_retry_config() {
        return array(
            'enabled'       => true,
            'max_attempts'  => 2,
            'initial_delay' => 1,
            'exponential'   => true,
            'jitter'        => true,
        );
    }

    /** @return array<string,mixed> */
    public function get_circuit_breaker_config() {
        return $this->config->get_circuit_breaker_config();
    }

    /** @return array<string,mixed> */
    public function get_rate_limit_config() {
        return $this->config->get_rate_limit_config();
    }
}

/**
 * In-memory mapping store for integration stress-test cases.
 *
 * The Integration Manager loads a template's field mappings through a
 * repository; the stress test never persists mappings, so this stand-in hands
 * the manager a fixed set of mapping rows for any template id. It only needs to
 * satisfy the one method the manager calls, get_by_template().
 */
class AIPS_Stress_Test_Fixed_Mappings_Repository {

    /** @var array<int, object> */
    private $mappings;

    /**
     * @param array<int, object> $mappings Mapping rows to return for any template.
     */
    public function __construct(array $mappings) {
        $this->mappings = $mappings;
    }

    /**
     * @param int  $template_id Ignored; the same fixed set is always returned.
     * @param bool $active_only Ignored.
     * @return array<int, object>
     */
    public function get_by_template($template_id, $active_only = true) {
        return $this->mappings;
    }
}

